const I18N_STORAGE_KEY = 'motortrends_lang';

function getCurrentLanguage() {
  const saved = localStorage.getItem(I18N_STORAGE_KEY);
  if (saved && I18N_TRANSLATIONS[saved]) {
    return saved;
  }
  return 'en';
}

function t(key, defaultVal = '') {
  const lang = getCurrentLanguage();
  if (I18N_TRANSLATIONS[lang] && I18N_TRANSLATIONS[lang][key]) {
    return I18N_TRANSLATIONS[lang][key];
  }
  if (I18N_TRANSLATIONS.en && I18N_TRANSLATIONS.en[key]) {
    return I18N_TRANSLATIONS.en[key];
  }
  return defaultVal || key;
}

// Ensure currency is strictly formatted in CAD without restriction or rounding
function formatCAD(amount) {
  if (amount === undefined || amount === null || amount === '') return '$0 CAD';
  const str = String(amount).trim();
  const num = parseFloat(str);
  if (isNaN(num)) return `$${amount} CAD`;
  if (str.includes('.')) {
    const parts = str.split('.');
    const intVal = parseInt(parts[0], 10);
    const formattedInt = isNaN(intVal) ? parts[0] : intVal.toLocaleString('en-CA');
    return `$${formattedInt}.${parts[1]} CAD`;
  }
  return `$${num.toLocaleString('en-CA')} CAD`;
}

function formatCADMonthly(amount) {
  if (amount === undefined || amount === null || amount === '') return '$0 CAD/mo';
  const str = String(amount).trim();
  const num = parseFloat(str);
  if (isNaN(num)) return `$${amount} CAD/mo`;
  if (str.includes('.')) {
    const parts = str.split('.');
    const intVal = parseInt(parts[0], 10);
    const formattedInt = isNaN(intVal) ? parts[0] : intVal.toLocaleString('en-CA');
    return `$${formattedInt}.${parts[1]} CAD/mo`;
  }
  return `$${num.toLocaleString('en-CA')} CAD/mo`;
}

function applyTranslations(lang = getCurrentLanguage()) {
  const dict = I18N_TRANSLATIONS[lang] || I18N_TRANSLATIONS.en;
  
  // Update elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  // Update elements with data-i18n-html
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (dict[key]) {
      el.innerHTML = dict[key];
    }
  });

  // Update placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) {
      el.setAttribute('placeholder', dict[key]);
    }
  });

  // Sync select element
  const langSelectors = document.querySelectorAll('.lang-select');
  langSelectors.forEach(sel => {
    sel.value = lang;
  });

  // Set document lang attribute
  document.documentElement.lang = lang;

  // Dispatch global event for components (e.g., inventory renderer, slideshow)
  window.dispatchEvent(new CustomEvent('motortrends:languageChanged', { detail: { lang } }));
}

function changeLanguage(lang) {
  if (!I18N_TRANSLATIONS[lang]) lang = 'en';
  localStorage.setItem(I18N_STORAGE_KEY, lang);
  applyTranslations(lang);
}

document.addEventListener('DOMContentLoaded', () => {
  const currentLang = getCurrentLanguage();
  applyTranslations(currentLang);
});
